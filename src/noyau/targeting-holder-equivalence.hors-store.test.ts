function* etats(): Generator<{ ligne: number; colonne: number; s: Jeu }> {
  const [k1, k2, k3, k4, k5, k6, k7] = Object.values(AXES);
  let ligne = 0;
  for (const a of k1) for (const b of k2) for (const c of k3) for (const d of k4) for (const e of k5) {
    let colonne = 0;
    for (const f of k6) for (const g of k7) {
      const s = { pendingCleave: a, pendingDualStrike: b, pendingAttack: c, pendingCast: d, pendingSiegeAim: e, pendingCascade: f, battle: g };
      yield { ligne, colonne, s: s as unknown as Jeu };
      colonne++;
    }
    ligne++;
  }
}

const issueDe = (s: Jeu) =>
  `${targetingHolder(s) ?? '-'} ${currentTargetingMode(() => s).id} ${JSON.stringify(placingZoneOf(s))}`;

describe('détenteur du ciblage : possession, aiguilleur et gabarit sur la matrice de base', () => {
  it('chaque état rend son issue attendue', () => {
    const ecarts: string[] = [];
    for (const { ligne, colonne, s } of etats()) {
      const attendu = ISSUES[CODES.indexOf(ATTENDU[ligne][colonne])];
      const obtenu = issueDe(s);
      if (obtenu !== attendu && ecarts.length < 5) ecarts.push(`[${ligne}:${colonne}] attendu « ${attendu} », obtenu « ${obtenu} » sur ${JSON.stringify(s)}`);
    }
    expect(ecarts).toEqual([]);
  });

  it('chaque TARGETING_HOLDERS est produit par un état et inscrit à HORS_MODAL', () => {
    const produits = new Set<string>();
    for (const { s } of etats()) {
      const h = targetingHolder(s);
      if (h) produits.add(h);
    }
    expect([...produits].sort()).toEqual([...TARGETING_HOLDERS].sort());
    const registre = horsModalByPending();
    expect(TARGETING_HOLDERS.filter((k) => !registre[k])).toEqual([]);
  });
});
